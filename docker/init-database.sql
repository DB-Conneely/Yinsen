\getenv migration_password MIGRATION_PASSWORD
\getenv runtime_password RUNTIME_PASSWORD
CREATE ROLE yinsen_migrator LOGIN PASSWORD :'migration_password' NOSUPERUSER NOCREATEDB NOCREATEROLE;
CREATE ROLE yinsen_runtime LOGIN PASSWORD :'runtime_password' NOSUPERUSER NOCREATEDB NOCREATEROLE;
ALTER DATABASE yinsen OWNER TO yinsen_migrator;
REVOKE ALL ON DATABASE yinsen FROM PUBLIC;
GRANT CONNECT ON DATABASE yinsen TO yinsen_runtime;
ALTER SCHEMA public OWNER TO yinsen_migrator;
REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO yinsen_runtime;
ALTER DEFAULT PRIVILEGES FOR ROLE yinsen_migrator IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO yinsen_runtime;
ALTER DEFAULT PRIVILEGES FOR ROLE yinsen_migrator IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO yinsen_runtime;
